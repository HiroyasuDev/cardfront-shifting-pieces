#!/usr/bin/env python3
"""SYNTHETIC: one local vision-model caption per persona screenshot (Ollama qwen2.5vl:3b, keep_alive=0).

The colourblind persona (p08) is shown its deuteranopia-simulated screenshot.
Output: feedback/vision_captions.json  — all text is model-generated (SYNTHETIC).
"""
import base64
import io
import json
import os
import sys
import time
import urllib.request

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OLLAMA = "http://127.0.0.1:11434"
MODEL = os.environ.get("VISION_MODEL", "qwen2.5vl:3b")
PROMPT = (
    "This is a screenshot of a digital tactics card game (3x3 board, hand of cards on the left, dice panel on the right). "
    "Look carefully and answer ONLY with a JSON object with these keys: "
    '"player_vs_enemy_distinguishable" (yes/no/partly), "how_ownership_is_shown" (short), '
    '"edge_numbers_readable" (yes/no/partly), "most_eye_catching_element" (short), '
    '"visual_clutter_1to10" (integer), "anything_cut_off_or_overlapping" (short), "art_style" (short).'
)


def pick(summary):
    shots = summary["screenshots"]
    pid = summary["persona"]
    pref = [s for s in shots if "_s4_m1_mid" in s or "_s4_m1_dragmid" in s] or [s for s in shots if "_mid" in s] or shots
    s = pref[0]
    if pid == "p08":
        cand = s.replace(".jpg", "_deutan.jpg")
        if os.path.exists(os.path.join(ROOT, cand)):
            s = cand
    return s


def b64img(path, width=1024):
    im = Image.open(path).convert("RGB")
    im = im.resize((width, int(im.height * width / im.width)))
    buf = io.BytesIO()
    im.save(buf, "JPEG", quality=80)
    return base64.b64encode(buf.getvalue()).decode()


def ask(img_b64, keep_alive):
    body = json.dumps({"model": MODEL, "prompt": PROMPT, "images": [img_b64], "stream": False, "format": "json",
                       "keep_alive": keep_alive, "options": {"temperature": 0.2, "num_ctx": 4096, "seed": 7}}).encode()
    req = urllib.request.Request(OLLAMA + "/api/generate", data=body, headers={"Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=600) as r:
        return json.loads(r.read())


def main():
    sums = json.load(open(os.path.join(ROOT, "raw", "persona_summaries.json")))
    out = {"_note": "SYNTHETIC — generated by local vision model " + MODEL + " via Ollama; not human feedback.", "captions": {}}
    pids = list(sums)
    for i, pid in enumerate(pids):
        shot = pick(sums[pid])
        t0 = time.time()
        keep = "5m" if i < len(pids) - 1 else 0  # keep loaded across the batch, unload after the last call
        try:
            r = ask(b64img(os.path.join(ROOT, shot)), keep)
            txt = r.get("response", "")
            try:
                parsed = json.loads(txt)
            except Exception:
                parsed = None
            out["captions"][pid] = {"screenshot": shot, "raw": txt, "parsed": parsed, "seconds": round(time.time() - t0, 1)}
        except Exception as e:
            out["captions"][pid] = {"screenshot": shot, "error": str(e)}
        print(pid, shot, out["captions"][pid].get("seconds"), (out["captions"][pid].get("raw") or out["captions"][pid].get("error", ""))[:200])
    # make sure the model is unloaded (8 GB machine: one model at a time)
    try:
        ask_body = json.dumps({"model": MODEL, "keep_alive": 0}).encode()
        urllib.request.urlopen(urllib.request.Request(OLLAMA + "/api/generate", data=ask_body,
                                                      headers={"Content-Type": "application/json"}), timeout=60).read()
    except Exception:
        pass
    os.makedirs(os.path.join(ROOT, "feedback"), exist_ok=True)
    json.dump(out, open(os.path.join(ROOT, "feedback", "vision_captions.json"), "w"), indent=2)


if __name__ == "__main__":
    sys.exit(main())
