#!/usr/bin/env python3
"""SYNTHETIC persona feedback: local MLX Qwen2.5-3B-Instruct-4bit (one model, loaded once, then freed).

Input per persona: its OWN objective telemetry facts (facts.py) + optional SYNTHETIC vision caption.
Output: feedback/persona_feedback.json — every rating/like/frustration/quote is LLM-generated (SYNTHETIC).
"""
import gc
import json
import os
import re
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from facts import GAME_FACTS, facts  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODEL = os.environ.get("FEEDBACK_MODEL", "mlx-community/Qwen2.5-3B-Instruct-4bit")
RATING_KEYS = ["fun", "rules_clarity", "board_readability", "difficulty_fairness", "strategic_depth",
               "drag_drop_feel", "art", "replay_intent"]

SCHEMA_TXT = (
    '{"ratings": {"fun": 1-10, "rules_clarity": 1-10, "board_readability": 1-10, "difficulty_fairness": 1-10, '
    '"strategic_depth": 1-10, "drag_drop_feel": 1-10, "art": 1-10, "replay_intent": 1-10}, "nps": 0-10, '
    '"likes": ["...", "...", "..."], "frustrations": ["...", "...", "..."], "quote": "..."}'
)


def build_messages(P, s, caption):
    sys_msg = (
        f"You are role-playing a game playtester persona: {P['name']} — {P['archetype']}. {P['voice']} "
        "You just finished a playtest session. Give honest feedback IN CHARACTER, but every like and frustration must be "
        "grounded in the GAME FACTS and SESSION TELEMETRY you are given. Do not invent features, modes, events, or numbers "
        "that are not in those facts. Ratings are integers from 1 to 10; NPS is an integer from 0 to 10. "
        "Reply with ONLY a JSON object of this shape: " + SCHEMA_TXT
    )
    user = GAME_FACTS + "\n\n" + facts(s)
    if caption:
        user += "\n\nWHAT YOU SAW (a screenshot description from a vision model; may be imprecise): " + json.dumps(caption)
    user += "\n\nNow write your feedback JSON."
    return [{"role": "system", "content": sys_msg}, {"role": "user", "content": user}]


def parse(txt):
    m = re.search(r"\{.*\}", txt, re.S)
    if not m:
        return None, "no json"
    try:
        d = json.loads(m.group(0))
    except Exception as e:
        return None, f"bad json: {e}"
    r = d.get("ratings", {})
    try:
        d["ratings"] = {k: int(r[k]) for k in RATING_KEYS}
        d["nps"] = int(d["nps"])
    except Exception as e:
        return None, f"missing field: {e}"
    if not all(1 <= v <= 10 for v in d["ratings"].values()) or not 0 <= d["nps"] <= 10:
        return None, "out of range"
    if len(d.get("likes", [])) < 3 or len(d.get("frustrations", [])) < 3 or not d.get("quote"):
        return None, "lists"
    d["likes"], d["frustrations"] = [str(x) for x in d["likes"][:3]], [str(x) for x in d["frustrations"][:3]]
    return d, None


def main():
    import subprocess
    from mlx_lm import generate, load
    from mlx_lm.sample_utils import make_sampler

    personas = {p["id"]: p for p in json.loads(subprocess.check_output(
        ["/Users/frederickamina/.local/bin/node", "-e", "console.log(JSON.stringify(require('./personas.js')))"],
        cwd=os.path.join(ROOT, "scripts")))}
    sums = json.load(open(os.path.join(ROOT, "raw", "persona_summaries.json")))
    cap_path = os.path.join(ROOT, "feedback", "vision_captions.json")
    caps = json.load(open(cap_path))["captions"] if os.path.exists(cap_path) else {}
    model, tok = load(MODEL)
    out = {"_note": f"SYNTHETIC — generated by local {MODEL} (MLX) role-playing each persona from its own telemetry. Not human feedback.",
           "model": MODEL, "feedback": {}}
    for pid, s in sums.items():
        P = personas[pid]
        cap = (caps.get(pid) or {}).get("parsed")
        msgs = build_messages(P, s, cap)
        prompt = tok.apply_chat_template(msgs, tokenize=False, add_generation_prompt=True)
        fb, err, attempts, raw = None, None, 0, ""
        t0 = time.time()
        for temp in (0.7, 0.5, 0.3):
            attempts += 1
            raw = generate(model, tok, prompt=prompt, max_tokens=700, sampler=make_sampler(temp=temp, top_p=0.9), verbose=False)
            fb, err = parse(raw)
            if fb:
                break
        out["feedback"][pid] = {"persona": P["name"], "synthetic": True, "attempts": attempts, "seconds": round(time.time() - t0, 1),
                                "used_vision_caption": bool(cap), "parse_error": err, "raw": raw if not fb else None, **(fb or {})}
        print(pid, P["name"], "ok" if fb else f"FAILED {err}", (fb or {}).get("ratings"), (fb or {}).get("nps"))
    del model, tok
    gc.collect()
    try:
        import mlx.core as mx
        mx.clear_cache()
    except Exception:
        pass
    json.dump(out, open(os.path.join(ROOT, "feedback", "persona_feedback.json"), "w"), indent=2, ensure_ascii=False)


if __name__ == "__main__":
    sys.exit(main())
